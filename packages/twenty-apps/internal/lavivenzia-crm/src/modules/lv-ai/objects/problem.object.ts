// The Problem database from DATA-MODEL.md ("Type, severity, lead, reporter,
// description, root cause, status, resolution, AI recommendation"). Until
// Day 6 objections lived only as free text on an interaction; this object
// gives a confirmed business problem a life of its own — tracked, resolved,
// and counted in the Control Tower.
//
// AI may SUGGEST a problem (an lvAiInsight of type PROBLEM_SUGGESTION). A row
// here is created only when a person confirms that suggestion, through the
// decide route, with that person recorded as the reporter. The AI
// recommendation is kept as advice, clearly labelled, never as the resolution.

export const PROBLEM_STATUSES = ['OPEN', 'IN_PROGRESS', 'RESOLVED', 'DISMISSED'] as const;

export type ProblemStatus = (typeof PROBLEM_STATUSES)[number];

const option = (group: string, index: number, value: string, color: SelectOptionColor): SelectOption => ({
  id: `d6a${group}0000-0000-4000-8000-${String(index).padStart(12, '0')}`,
  value,
  label: value.charAt(0) + value.slice(1).toLowerCase().replace(/_/g, ' '),
  position: index,
  color,
});

const TYPE_OPTIONS: SelectOption[] = [...OBJECTION_CATEGORIES, 'DATA_QUALITY'].map((value, index) => option('6', index + 1, value, 'gray'));
const SEVERITY_OPTIONS: SelectOption[] = PROBLEM_SEVERITIES.map((value, index) =>
  option('7', index + 1, value, value === 'CRITICAL' ? 'red' : value === 'HIGH' ? 'orange' : value === 'MEDIUM' ? 'yellow' : 'gray'),
);
const STATUS_OPTIONS: SelectOption[] = PROBLEM_STATUSES.map((value, index) =>
  option('8', index + 1, value, value === 'RESOLVED' ? 'green' : value === 'DISMISSED' ? 'gray' : value === 'IN_PROGRESS' ? 'blue' : 'orange'),
);

