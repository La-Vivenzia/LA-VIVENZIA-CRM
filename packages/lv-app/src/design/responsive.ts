import { LV_BREAKPOINT } from 'src/design/tokens';

// The responsive contract.
//
// Mobile is a product, not a narrowed desktop. So every shared component in
// the La Vivenzia system declares here what it does at each of three widths,
// what the interaction *becomes* when the screen is small, how it stacks, what
// happens to overflow, and how large the thing you touch is.
//
// This file is the single source of truth for that contract: the design-system
// document is written from it and a unit test asserts that every family the
// system ships is present and internally consistent. A component whose
// behaviour is not written down here is not finished.
//
// The one implementation rule that makes all of it possible: an inline React
// style beats a media query, so anything that differs by width — direction,
// width, padding, type size, order — belongs in the stylesheet (`LvStyles`),
// and inline styles carry only what never changes, such as colour.

export type LvTier = 'mobile' | 'tablet' | 'desktop';

// Phones up to 767, tablets 768–1023, desktop from 1024. These are the QA
// widths in UI-UX-SPEC.md and the breakpoints the stylesheet switches on.
export const LV_TIERS: Record<LvTier, { min: number; max: number | null; label: string }> = {
  mobile: { min: 0, max: LV_BREAKPOINT.md - 1, label: 'Phone · up to 767px' },
  tablet: { min: LV_BREAKPOINT.md, max: LV_BREAKPOINT.lg - 1, label: 'Tablet · 768–1023px' },
  desktop: { min: LV_BREAKPOINT.lg, max: null, label: 'Desktop · 1024px and wider' },
};

export const tierFor = (width: number): LvTier => (width < LV_BREAKPOINT.md ? 'mobile' : width < LV_BREAKPOINT.lg ? 'tablet' : 'desktop');

/** The smallest square a finger is asked to hit. Nothing interactive goes below it. */
export const LV_TOUCH_TARGET = 44;

/** A secondary control inside a dense row may be this small, but no smaller. */
export const LV_TOUCH_TARGET_COMPACT = 36;

export type LvResponsiveSpec = {
  /** The family name, as the design system and the documentation call it. */
  family: string;
  /** Foundations are values; components are things you render. */
  kind: 'foundation' | 'component';
  /** The exported symbols that make up this family. */
  exports: string[];
  /** One line on what the family is for. */
  purpose: string;
  desktop: string;
  tablet: string;
  mobile: string;
  /** What the interaction itself becomes on a phone, where it changes. */
  interaction: string | null;
  /** How the parts reflow when the width runs out. */
  stacking: string;
  /** What happens to content that does not fit. */
  overflow: string;
  /** Minimum touch target in px, or null when nothing here is interactive. */
  touchTarget: number | null;
  /** True when this family docks to the bottom edge of a phone screen. */
  bottomSheet: boolean;
};

const spec = (value: LvResponsiveSpec): LvResponsiveSpec => value;

